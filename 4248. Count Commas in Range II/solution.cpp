class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000){
            return 0;
        }
        long long cnt=0;
        // 1,000 to 999,999
        if (n >= 1000 && n < 1000000) {
            cnt += (n - 1000) + 1;
        }

        
        
       // 1,000,000 to 999,999,999
        if (n >= 1000000 && n < 1000000000) {
            // Previous range: 1000 to 999999
            cnt += (999999 - 1000 + 1);

            // Current range: 1000000 to n
            cnt += ((n - 1000000) + 1) * 2;
        }

        // 1,000,000,000 to 999,999,999,999
        if (n >= 1000000000 && n < 1000000000000LL) {
            // Previous ranges
            cnt += (999999 - 1000 + 1);
            cnt += (999999999 - 1000000 + 1) * 2;

            // Current range
            cnt += ((n - 1000000000) + 1) * 3;
        }
         // 1,000,000,000,000 to 999,999,999,999,999
        if (n >= 1000000000000LL && n < 1000000000000000LL) {
            cnt += (999999 - 1000 + 1);
            cnt += (999999999 - 1000000 + 1) * 2;
            cnt += (999999999999LL - 1000000000 + 1) * 3;

            cnt += ((n - 1000000000000LL) + 1) * 4;
        }
         // 1,000,000,000,000,000 onwards
        if (n >= 1000000000000000LL) {
            cnt += (999999 - 1000 + 1);
            cnt += (999999999 - 1000000 + 1) * 2;
            cnt += (999999999999LL - 1000000000 + 1) * 3;
            cnt += (999999999999999LL - 1000000000000LL + 1) * 4;

            cnt += ((n - 1000000000000000LL) + 1) * 5;
        }

        return cnt;
    }
};